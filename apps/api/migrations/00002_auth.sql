GRANT USAGE ON SCHEMA auth TO fatbook_auth;
GRANT USAGE ON SCHEMA app TO fatbook_auth;

CREATE TABLE app.users (
    id uuid PRIMARY KEY,
    email text NOT NULL UNIQUE CHECK (email = lower(btrim(email)) AND length(email) BETWEEN 3 AND 254),
    personal_space_id bigint NOT NULL UNIQUE CHECK (personal_space_id BETWEEN 1 AND 9007199254740991)
);
CREATE TABLE app.spaces (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    owner_id uuid NOT NULL UNIQUE REFERENCES app.users(id) DEFERRABLE INITIALLY DEFERRED
);
ALTER TABLE app.users ADD FOREIGN KEY (personal_space_id) REFERENCES app.spaces(id) DEFERRABLE INITIALLY DEFERRED;
CREATE TABLE app.memberships (
    user_id uuid PRIMARY KEY REFERENCES app.users(id),
    space_id bigint NOT NULL UNIQUE REFERENCES app.spaces(id)
);
CREATE TABLE app.goals (
    user_id uuid PRIMARY KEY REFERENCES app.users(id),
    proteins double precision NOT NULL CHECK (proteins >= 0 AND proteins < 'Infinity'::double precision),
    fats double precision NOT NULL CHECK (fats >= 0 AND fats < 'Infinity'::double precision),
    carbs double precision NOT NULL CHECK (carbs >= 0 AND carbs < 'Infinity'::double precision),
    calories double precision NOT NULL CHECK (calories >= 0 AND calories < 'Infinity'::double precision)
);
CREATE TABLE app.dishes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (id BETWEEN 1 AND 9007199254740991),
    space_id bigint REFERENCES app.spaces(id),
    name text NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 100),
    icon text,
    proteins double precision NOT NULL CHECK (proteins >= 0 AND proteins < 'Infinity'::double precision),
    fats double precision NOT NULL CHECK (fats >= 0 AND fats < 'Infinity'::double precision),
    carbs double precision NOT NULL CHECK (carbs >= 0 AND carbs < 'Infinity'::double precision),
    calories double precision NOT NULL CHECK (calories >= 0 AND calories < 'Infinity'::double precision),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX dishes_space_id_idx ON app.dishes(space_id);

CREATE TABLE auth.passwords (
    user_id uuid PRIMARY KEY REFERENCES app.users(id),
    hash text NOT NULL
);
CREATE TABLE auth.sessions (
    token text PRIMARY KEY,
    data bytea NOT NULL,
    expiry timestamptz NOT NULL
);
CREATE INDEX sessions_expiry_idx ON auth.sessions(expiry);
